"""Write tools/freeze-requirements.txt: PyInstaller and everything it
installs, each at one version with the SHA-256 of every file PyPI has for it.

    python3 tools/pin_freeze.py              the latest versions
    python3 tools/pin_freeze.py 6.22.3       PyInstaller at this version

The frozen-build workflow installs from that file with `--require-hashes`, so
a file swapped on PyPI, or a dependency that was not reviewed, fails the
build instead of entering it. Every file's hash is listed, not just the ones
this machine would use, because the same file serves Linux, Windows and macOS.

The dependency list is PyInstaller's own (`requires_dist`), with its platform
markers kept. A new dependency in a later PyInstaller shows up as an install
error naming it; add it to DEPENDENCIES and run this again.
"""

from __future__ import annotations

import json
import pathlib
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "tools" / "freeze-requirements.txt"

# name -> environment marker ("" for everywhere); PyInstaller's own markers
DEPENDENCIES = {
    "altgraph": "",
    "packaging": "",
    "setuptools": "",
    "pyinstaller-hooks-contrib": "",
    "macholib": 'sys_platform == "darwin"',
    "pefile": 'sys_platform == "win32"',
    "pywin32-ctypes": 'sys_platform == "win32"',
}


def release(name: str, version: str | None = None) -> tuple[str, list[str]]:
    url = f"https://pypi.org/pypi/{name}/{version + '/' if version else ''}json"
    with urllib.request.urlopen(url, timeout=30) as response:
        data = json.load(response)
    hashes = sorted(f["digests"]["sha256"] for f in data["urls"] if not f.get("yanked"))
    return data["info"]["version"], hashes


def main(argv: list[str]) -> int:
    pinned = [("pyinstaller", "", *release("pyinstaller", argv[0] if argv else None))]
    pinned += [(name, marker, *release(name)) for name, marker in DEPENDENCIES.items()]
    lines = [
        "# Generated by tools/pin_freeze.py; do not edit by hand.",
        "# Installed with --require-hashes by .github/workflows/frozen.yml and make freeze.",
    ]
    for name, marker, version, hashes in pinned:
        lines.append(f"{name}=={version}" + (f" ; {marker}" if marker else "") + " \\")
        lines += [
            f"    --hash=sha256:{h}" + (" \\" if i < len(hashes) - 1 else "")
            for i, h in enumerate(hashes)
        ]
    OUT.write_text("\n".join(lines) + "\n")
    for name, _, version, hashes in pinned:
        print(f"  {name}=={version}  ({len(hashes)} files)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
