"""An exported Schema as SQL table definitions, in one dialect.

Input is the export file (`designer-export`, spec §9.6), never the model: the
export already has every rule resolved, inherited columns flattened and
reference columns named. Output is deterministic — no timestamp — so the same
export gives the same bytes, and the examples are compared byte for byte.

Every rule ends up in exactly one of three places, and the report says which:

- a named CHECK constraint, when the dialect can say exactly what the rule
  says;
- a comment beside the table, `NOT ENFORCED HERE`, when it cannot, with the
  reason — it must be enforced in the application;
- a comment saying it is the application's, when the export already put it
  there (cross-table, or reading the clock).

Appendix *ddl* describes the output in full.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from importlib import metadata
from typing import Any

from .dialects import Column, Dialect, MariaDB, PostgreSQL, SQLite, Untranslatable
from .translate import translate

FORMAT = "designer-schema-export"
FORMAT_VERSIONS = {1}
LANGUAGES = {"designer-1"}


class ExportFileError(ValueError):
    """The input is not an export file this version can read."""


@dataclass
class Report:
    """What did not become a constraint, for the person running the tool."""

    untranslated: list[str] = field(default_factory=list)
    application: list[str] = field(default_factory=list)
    storage: list[str] = field(default_factory=list)

    def lines(self) -> list[str]:
        out = []
        if self.untranslated:
            out.append(f"{len(self.untranslated)} rule(s) could not be written as a CHECK constraint:")
            out += [f"  {line}" for line in self.untranslated]
        if self.storage:
            out.append("storage notes:")
            out += [f"  {line}" for line in self.storage]
        if self.application:
            out.append(f"{len(self.application)} rule(s) are enforced by the application, as exported")
        return out


def version() -> str:
    try:
        return metadata.version("designer-ddl")
    except metadata.PackageNotFoundError:
        return "source"


def check_format(document: Any) -> None:
    if not isinstance(document, dict) or document.get("format") != FORMAT:
        raise ExportFileError(f'not a schema export: expected "format": "{FORMAT}"')
    if document.get("format_version") not in FORMAT_VERSIONS:
        raise ExportFileError(f"export format_version {document.get('format_version')!r} is not one this reads")
    language = document.get("source", {}).get("expression_language")
    if language not in LANGUAGES:
        raise ExportFileError(f"expression language {language!r} is not one this translates")


def _bare(sql: str) -> str:
    """Without one pair of outer parentheses, if they enclose the whole: a
    CHECK already brackets its condition."""
    if not (sql.startswith("(") and sql.endswith(")")):
        return sql
    depth, quote = 0, ""
    for i, ch in enumerate(sql):
        if quote:
            if ch == quote:
                quote = ""
        elif ch in "'\"`":
            quote = ch
        elif ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
            if depth == 0 and i != len(sql) - 1:
                return sql
    return sql[1:-1]


def _comment_text(text: str) -> str:
    return " ".join(str(text).split())


class Generator:
    def __init__(self, document: dict[str, Any], dialect: Dialect) -> None:
        check_format(document)
        self.doc = document
        self.d = dialect
        self.report = Report()
        self.out: list[str] = []
        self._names: set[str] = set()

    # --- the whole file -----------------------------------------------------

    def run(self) -> str:
        schema = self.doc["schema"]
        self._header(schema)
        foreign: list[str] = []
        for table in self.doc["tables"]:
            foreign += self._table(table)
        if foreign:
            self.out += ["-- Foreign keys, after every table exists.", *foreign, ""]
        self._schema_rules()
        while self.out and self.out[-1] == "":
            self.out.pop()
        return "\n".join(self.out) + "\n"

    def _header(self, schema: dict[str, Any]) -> None:
        source = self.doc["source"]
        self.out += [
            f"-- {schema['name']}, for {self.d.title}.",
            "-- Generated by designer-ddl from a designer-schema-export, format "
            f"{self.doc['format_version']}, expression language {source['expression_language']}.",
            "-- Regenerate it from the model rather than editing it.",
        ]
        if schema.get("description"):
            self.out.append(f"-- {_comment_text(schema['description'])}")
        if self.doc.get("warnings"):
            self.out.append("--")
            self.out.append("-- Warnings from the model check, carried by the export:")
            for w in self.doc["warnings"]:
                self.out.append(f"--   {w['code']} {w['item']}: {_comment_text(w['message'])}")
        self.out.append("")
        if isinstance(self.d, SQLite):
            self.out += [
                "-- SQLite checks foreign keys only where each connection asks it to.",
                "PRAGMA foreign_keys = ON;",
                "",
            ]

    # --- one table ----------------------------------------------------------

    def _columns(self, table: dict[str, Any]) -> dict[str, Column]:
        unbounded = {c["name"] for c in table["columns"] if c["base"] == "string" and not c.get("length")}
        keys: list[list[str]] = [table.get("primary_key", [])]
        keys += [fk["columns"] for fk in table.get("foreign_keys", [])]
        keys += [index["columns"] for index in table.get("indexes", [])]
        # a column that a foreign key elsewhere points at is keyed too
        for other in self.doc["tables"]:
            keys += [fk["target_columns"] for fk in other.get("foreign_keys", []) if fk["table"] == table["name"]]
        share: dict[str, int] = {}
        for key in keys:
            wide = sum(1 for name in key if name in unbounded)
            for name in key:
                share[name] = max(share.get(name, 0), wide or 1)
        out = {}
        for c in table["columns"]:
            numeric = c.get("numeric") or {}
            out[c["name"]] = Column(
                c["name"], c["base"], c.get("length"), numeric.get("precision"), numeric.get("scale"),
                share.get(c["name"], 0),
            )  # fmt: skip
        return out

    def _unique(self, *parts: str) -> str:
        name = self.d.constraint_name(*parts)
        n = 2
        while name in self._names:
            name = self.d.constraint_name(*parts, str(n))
            n += 1
        self._names.add(name)
        return name

    def _table(self, table: dict[str, Any]) -> list[str]:
        d = self.d
        tname = table["name"]
        columns = self._columns(table)
        lines: list[str] = []  # the body of CREATE TABLE, each without its comma
        comments: list[str] = []  # what goes after the statement
        after: list[str] = []

        if table.get("description"):
            self.out.append(f"-- {_comment_text(table['description'])}")
        if table.get("inherits"):
            self.out.append(f"-- Includes the columns of {', '.join(table['inherits'])} (flattened: no shared table).")

        for c in table["columns"]:
            column = columns[c["name"]]
            try:
                kind, type_checks, notes = d.column_type(column)
            except Untranslatable as why:
                raise ExportFileError(f"{tname}.{c['name']}: {why}") from why
            text = f"{d.ident(c['name'])} {kind}"
            if not c.get("nullable", True):
                text += " NOT NULL"
            if c.get("default") is not None:
                text += f" DEFAULT {d.default(c['default'])}"
            if isinstance(d, MariaDB) and c.get("description"):
                text += f" COMMENT {d.string(_comment_text(c['description']))}"
            entry = [text]
            for note in notes:
                entry.insert(0, f"-- {c['name']}: {note}")
                self.report.storage.append(f"{tname}.{c['name']}: {note}")
            lines += entry
            for check in type_checks:
                name = self._unique(tname, c["name"], "type")
                lines.append(f"CONSTRAINT {d.ident(name)} CHECK ({check})")
            if isinstance(d, PostgreSQL) and c.get("description"):
                after.append(
                    f"COMMENT ON COLUMN {d.ident(tname)}.{d.ident(c['name'])} IS "
                    f"{d.string(_comment_text(c['description']))};"
                )

        if table.get("primary_key"):
            name = self._unique(tname, "pkey")
            keys = ", ".join(d.ident(k) for k in table["primary_key"])
            lines.append(f"CONSTRAINT {d.ident(name)} PRIMARY KEY ({keys})")

        for c in table["columns"]:
            for rule in c.get("check", []):
                lines += self._check(tname, columns, rule, column=c["name"])
            for rule in c.get("application", []):
                comments.append(self._application(tname, rule, c["name"]))
        for rule in table.get("check", []):
            lines += self._check(tname, columns, rule)
        for rule in table.get("application", []):
            comments.append(self._application(tname, rule))

        foreign = []
        for fk in table.get("foreign_keys", []):
            name = self._unique(tname, fk["relationship"], "fkey")
            clause = (
                f"FOREIGN KEY ({', '.join(d.ident(x) for x in fk['columns'])}) "
                f"REFERENCES {d.ident(fk['table'])} ({', '.join(d.ident(x) for x in fk['target_columns'])}) "
                f"ON DELETE {fk['on_delete'].replace('_', ' ').upper()}"
            )
            if isinstance(d, SQLite):
                # SQLite cannot add a constraint to a table afterwards
                lines.append(f"CONSTRAINT {d.ident(name)} {clause}")
            else:
                foreign.append(f"ALTER TABLE {d.ident(tname)} ADD CONSTRAINT {d.ident(name)} {clause};")

        self.out.append(f"CREATE TABLE {d.ident(tname)} (")
        real = [i for i, line in enumerate(lines) if not line.startswith("--")]
        for i, line in enumerate(lines):
            comma = "," if real and i in real and i != real[-1] else ""
            self.out.append(f"    {line}{comma}")
        if isinstance(d, MariaDB):
            tail = ") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_nopad_bin"
            if table.get("description"):
                tail += f" COMMENT={d.string(_comment_text(table['description']))}"
            self.out.append(tail + ";")
        else:
            self.out.append(");")
        if isinstance(d, PostgreSQL) and table.get("description"):
            self.out.append(f"COMMENT ON TABLE {d.ident(tname)} IS {d.string(_comment_text(table['description']))};")
        self.out += after

        for index in table.get("indexes", []):
            unique = "UNIQUE " if index.get("unique") else ""
            name = self._unique(tname, *index["columns"], "key" if unique else "idx")
            self.out.append(
                f"CREATE {unique}INDEX {d.ident(name)} ON {d.ident(tname)} "
                f"({', '.join(d.ident(x) for x in index['columns'])});"
            )
        if table.get("default_order"):
            order = ", ".join(
                f"{o['column']} {'ascending' if o.get('ascending', True) else 'descending'}"
                for o in table["default_order"]
            )
            self.out.append(f"-- Default order, for queries: {order}.")
        self.out += comments
        self.out.append("")
        return foreign

    def _check(
        self, tname: str, columns: dict[str, Column], rule: dict[str, Any], column: str | None = None
    ) -> list[str]:
        where = f"{tname}.{column}" if column else tname
        label = f"{rule['rule']}" + (f" (from {rule['from']})" if rule.get("from") else "")
        try:
            sql = translate(rule["expression"], self.d, columns, value=column)
        except Untranslatable as why:
            self.report.untranslated.append(f"{where}: {label}: {rule['expression']} — {why}")
            return [
                f"-- NOT ENFORCED HERE, enforce in the application: {label}: {rule['expression']}",
                f"--   {why}",
            ]
        name = self._unique(tname, column or "", rule["rule"])
        out = []
        if rule.get("message"):
            out.append(f"-- {label}: {_comment_text(rule['message'])}")
        out.append(f"CONSTRAINT {self.d.ident(name)} CHECK ({_bare(sql)})")
        return out

    def _application(self, tname: str, rule: dict[str, Any], column: str | None = None) -> str:
        where = f"{tname}.{column}" if column else tname
        self.report.application.append(f"{where}: {rule['rule']}")
        reason = f" ({rule['reason']})" if rule.get("reason") else ""
        message = f" — {_comment_text(rule['message'])}" if rule.get("message") else ""
        return f"-- Enforced by the application{reason}: {rule['rule']}: {rule['expression']}{message}"

    def _schema_rules(self) -> None:
        rules = self.doc.get("application", [])
        if not rules:
            return
        self.out.append("-- Rules across tables, enforced by the application:")
        for rule in rules:
            self.report.application.append(f"{rule.get('anchor', '')}: {rule['rule']}")
            message = f" — {_comment_text(rule['message'])}" if rule.get("message") else ""
            self.out.append(f"--   {rule.get('anchor', '')}: {rule['rule']}: {rule['expression']}{message}")
        self.out.append("")


def generate(document: dict[str, Any], dialect: Dialect) -> tuple[str, Report]:
    generator = Generator(document, dialect)
    return generator.run(), generator.report
